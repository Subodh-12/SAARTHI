from __future__ import annotations

import tempfile
from pathlib import Path

import pytest
from sqlalchemy import text

from app.adapters.persistence import Persistence, _normalize_schema_sql, run_migrations
from app.core.settings import Settings


@pytest.mark.asyncio
async def test_sqlite_schema_migration_creates_core_tables():
    tmp = tempfile.NamedTemporaryFile(suffix=".db", delete=False)
    tmp.close()
    try:
        settings = Settings(
            persistence_backend="sqlite",
            database_url=f"sqlite+aiosqlite:///{tmp.name}",
        )
        from app.core.settings import reset_settings_cache

        reset_settings_cache()
        p = Persistence.from_settings()
        await run_migrations(p)
        async with p.session() as s:
            result = await s.execute(
                text("SELECT name FROM sqlite_master WHERE type='table' AND name='learner_profiles'")
            )
            assert result.scalar_one() == "learner_profiles"
        await p.dispose()
    finally:
        Path(tmp.name).unlink(missing_ok=True)


def test_postgres_database_url_requires_postgres_scheme():
    with pytest.raises(ValueError):
        Settings(
            persistence_backend="postgres",
            database_url="sqlite+aiosqlite:///tmp/test.db",
        )


def test_postgres_database_url_accepts_asyncpg_url():
    settings = Settings(
        persistence_backend="postgres",
        database_url="postgresql+asyncpg://saarthi:saarthi@localhost:5432/saarthi",
    )
    assert settings.database_url == "postgresql+asyncpg://saarthi:saarthi@localhost:5432/saarthi"


def test_postgres_schema_translation_replaces_sqlite_specific_ddl():
    sql = "CREATE TABLE glossary (glossary_id INTEGER PRIMARY KEY AUTOINCREMENT, blob_col BLOB);"
    translated = _normalize_schema_sql(sql, postgres=True)
    assert "GENERATED BY DEFAULT AS IDENTITY" in translated
    assert "BYTEA" in translated
    assert "AUTOINCREMENT" not in translated
